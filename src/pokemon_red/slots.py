"""Named snapshots with atomic publication and preserved overwrite history."""
from __future__ import annotations
from datetime import datetime, timezone
from dataclasses import dataclass
import json
from pathlib import Path
import uuid
import hashlib

from .engine import Game, ROM_SHA1, atomic_bytes
from .persistence import SaveSnapshot, sync_directory
from .editions import rom_sha1
from .telemetry import read_state


@dataclass(frozen=True)
class SlotSnapshot:
    directory: Path
    snapshot: SaveSnapshot
    preview: bytes
    metadata: bytes
    slot_id: str | None = None
    pointer: Path | None = None

    def publish(self):
        self.directory.mkdir(parents=True, exist_ok=False)
        self.snapshot.publish(self.directory)
        atomic_bytes(self.directory / "preview.ppm", self.preview, durable=True)
        atomic_bytes(self.directory / "metadata.json", self.metadata, durable=True)
        if self.pointer is not None:
            atomic_bytes(self.pointer, json.dumps({"generation": self.directory.name}).encode(), durable=True)
        # Persist newly created slot/generation/backup directory entries too.
        for parent in self.directory.parents:
            sync_directory(parent)
            if parent.name == 'Data':
                break
        return self.slot_id if self.slot_id is not None else self.directory


class Slots:
    def __init__(self, root: Path):
        self.root = Path(root)
        self.folder = self.root / "Data/slots"
        self.folder.mkdir(parents=True, exist_ok=True)

    @staticmethod
    def _name(name):
        name = name.strip()
        if not name or len(name) > 64:
            raise ValueError("Название слота должно содержать от 1 до 64 символов.")
        return name

    def _directory(self, slot_id):
        # IDs are generated by us; never use a display name as a file path.
        if not isinstance(slot_id, str) or len(slot_id) != 32 or any(c not in "0123456789abcdef" for c in slot_id):
            raise ValueError("Некорректный идентификатор слота")
        return self.folder / slot_id

    def _capture(self, game: Game, directory: Path, name: str, *, slot_id=None, pointer=None):
        state = read_state(game)
        snapshot = game.capture_save(metadata=False)
        metadata = {"name": name, "created_at": datetime.now(timezone.utc).isoformat(),
                    "rom_sha1": game.rom_sha1, "telemetry": state}
        return SlotSnapshot(directory, snapshot, b"P6\n240 160\n255\n" + game.rgb(),
                            (json.dumps(metadata, ensure_ascii=False, indent=2) + "\n").encode(),
                            slot_id, pointer)

    def capture(self, game: Game, name: str, slot_id: str | None = None) -> SlotSnapshot:
        name = self._name(name)
        slot_id = slot_id or uuid.uuid4().hex
        folder = self._directory(slot_id)
        return self._capture(game, folder / uuid.uuid4().hex, name,
                             slot_id=slot_id, pointer=folder / "current.json")

    def save(self, game: Game, name: str, slot_id: str | None = None) -> str:
        return self.capture(game, name, slot_id).publish()

    def get(self, slot_id: str) -> dict:
        folder = self._directory(slot_id)
        generation = json.loads((folder / "current.json").read_text())["generation"]
        if not isinstance(generation, str) or len(generation) != 32 or any(c not in "0123456789abcdef" for c in generation):
            raise ValueError("Повреждён указатель слота")
        directory = folder / generation
        metadata = json.loads((directory / "metadata.json").read_text())
        if metadata.get("rom_sha1") != rom_sha1(self.root):
            raise ValueError("Слот создан для другой версии игры")
        return dict(metadata, id=slot_id, directory=directory)

    def list(self) -> list[dict]:
        result = []
        for pointer in self.folder.glob("*/current.json"):
            try:
                result.append(self.get(pointer.parent.name))
            except (ValueError, KeyError, OSError):
                continue
        return sorted(result, key=lambda slot: slot["created_at"], reverse=True)

    def prepare_load(self, slot_id: str) -> Game:
        slot = self.get(slot_id)
        return self.prepare_backup(slot["directory"])

    def prepare_backup(self, directory: Path) -> Game:
        directory = Path(directory).resolve()
        if not (directory.is_relative_to(self.folder.resolve()) or
                directory.is_relative_to((self.root / "Data/backups/actions").resolve()) or
                directory.is_relative_to((self.root / 'Data/rewind').resolve()) or
                directory.is_relative_to((self.root / "Data/backups/autosaves").resolve())):
            raise ValueError("Резервная копия находится вне проекта")
        metadata = json.loads((directory / "metadata.json").read_text())
        if metadata.get("rom_sha1") != rom_sha1(self.root):
            raise ValueError("Копия создана для другой версии игры")
        candidate = Game(self.root, resume=False)
        try:
            candidate.load_state(directory / ('state.z' if (directory/'state.z').is_file() else 'FireRed.state'))
            candidate.advance(1)  # Populate framebuffer for the destination window.
        except BaseException:
            candidate.close()
            raise
        return candidate

    def backups(self) -> list[dict]:
        current = {slot["directory"] for slot in self.list()}
        paths = list((self.root / "Data/backups/actions").glob("*/metadata.json"))
        paths += list((self.root / "Data/backups/autosaves").glob("*/metadata.json"))
        paths += [path for path in self.folder.glob("*/*/metadata.json") if path.parent not in current]
        records = []
        for path in paths:
            try:
                metadata = json.loads(path.read_text())
                if metadata.get("rom_sha1") != rom_sha1(self.root):
                    continue
                identifier = "backup-" + hashlib.sha256(str(path.relative_to(self.root)).encode()).hexdigest()[:24]
                records.append(dict(metadata, id=identifier, directory=path.parent, is_backup=True))
            except (ValueError, OSError):
                continue
        from .save_timeline import SaveTimeline
        for row in SaveTimeline(self.root/'Data').records():
            records.append(dict(row,telemetry=row.get('summary')))
        return sorted(records, key=lambda record: record["created_at"], reverse=True)

    def capture_backup(self, game: Game, reason: str) -> SlotSnapshot:
        folder = self.root / "Data/backups/actions" / (datetime.now().strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:8])
        return self._capture(game, folder, reason)

    def backup(self, game: Game, reason: str) -> Path:
        return self.capture_backup(game, reason).publish()
